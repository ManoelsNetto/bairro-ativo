-- Dois perfis com tabelas próprias:
--   BA_CIDADAO  -> registra e apoia ocorrências
--   BA_SERVIDOR -> servidor público de um órgão; atende as ocorrências das categorias do seu órgão
--
-- Como rodar: abra no SQL Developer e execute como script (F5).
-- O script pode ser executado várias vezes: o bloco abaixo apaga as
-- tabelas do projeto (prefixo BA_) antes de criá-las de novo.
-- =====================================================================

BEGIN
  FOR t IN (SELECT table_name FROM user_tables
            WHERE table_name IN ('BA_ATUALIZACAO', 'BA_APOIO', 'BA_OCORRENCIA', 'BA_USUARIO',
                                 'BA_CIDADAO', 'BA_SERVIDOR', 'BA_CATEGORIA', 'BA_ORGAO', 'BA_BAIRRO')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- 1. TABELAS
-- ---------------------------------------------------------------------

-- Bairros atendidos pela plataforma
CREATE TABLE BA_BAIRRO (
  ID_BAIRRO   NUMBER(10)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOME        VARCHAR2(80) NOT NULL,
  ZONA        VARCHAR2(10) NOT NULL,
  CIDADE      VARCHAR2(60) DEFAULT 'São Paulo' NOT NULL,
  CONSTRAINT PK_BA_BAIRRO PRIMARY KEY (ID_BAIRRO),
  CONSTRAINT UK_BA_BAIRRO_NOME UNIQUE (NOME, CIDADE),
  CONSTRAINT CK_BA_BAIRRO_ZONA CHECK (ZONA IN ('CENTRO', 'NORTE', 'SUL', 'LESTE', 'OESTE'))
);

-- Órgãos públicos que atendem as ocorrências (cada um cuida de algumas categorias)
CREATE TABLE BA_ORGAO (
  ID_ORGAO   NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOME       VARCHAR2(80)  NOT NULL,
  SIGLA      VARCHAR2(10)  NOT NULL,
  TELEFONE   VARCHAR2(20),
  CONSTRAINT PK_BA_ORGAO PRIMARY KEY (ID_ORGAO),
  CONSTRAINT UK_BA_ORGAO_NOME UNIQUE (NOME),
  CONSTRAINT UK_BA_ORGAO_SIGLA UNIQUE (SIGLA)
);

-- Tipos de problema, o prazo de atendimento esperado e o órgão responsável
CREATE TABLE BA_CATEGORIA (
  ID_CATEGORIA NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOME         VARCHAR2(60)  NOT NULL,
  DESCRICAO    VARCHAR2(200),
  PRAZO_DIAS   NUMBER(3)     NOT NULL,
  ID_ORGAO     NUMBER(10)    NOT NULL,
  CONSTRAINT PK_BA_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
  CONSTRAINT UK_BA_CATEGORIA_NOME UNIQUE (NOME),
  CONSTRAINT FK_BA_CATEGORIA_ORGAO FOREIGN KEY (ID_ORGAO) REFERENCES BA_ORGAO (ID_ORGAO),
  CONSTRAINT CK_BA_CATEGORIA_PRAZO CHECK (PRAZO_DIAS BETWEEN 1 AND 365)
);

-- Cidadãos: moradores que registram e apoiam ocorrências
CREATE TABLE BA_CIDADAO (
  ID_CIDADAO   NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOME         VARCHAR2(100) NOT NULL,
  EMAIL        VARCHAR2(120) NOT NULL,
  TELEFONE     VARCHAR2(20),
  ID_BAIRRO    NUMBER(10)    NOT NULL,
  DT_CADASTRO  DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_BA_CIDADAO PRIMARY KEY (ID_CIDADAO),
  CONSTRAINT UK_BA_CIDADAO_EMAIL UNIQUE (EMAIL),
  CONSTRAINT FK_BA_CIDADAO_BAIRRO FOREIGN KEY (ID_BAIRRO) REFERENCES BA_BAIRRO (ID_BAIRRO)
);

-- Servidores públicos: atendem as ocorrências das categorias do seu órgão
CREATE TABLE BA_SERVIDOR (
  ID_SERVIDOR  NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOME         VARCHAR2(100) NOT NULL,
  EMAIL        VARCHAR2(120) NOT NULL,
  TELEFONE     VARCHAR2(20),
  MATRICULA    VARCHAR2(20)  NOT NULL,
  CARGO        VARCHAR2(60)  NOT NULL,
  ID_ORGAO     NUMBER(10)    NOT NULL,
  DT_CADASTRO  DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_BA_SERVIDOR PRIMARY KEY (ID_SERVIDOR),
  CONSTRAINT UK_BA_SERVIDOR_EMAIL UNIQUE (EMAIL),
  CONSTRAINT UK_BA_SERVIDOR_MATRICULA UNIQUE (MATRICULA),
  CONSTRAINT FK_BA_SERVIDOR_ORGAO FOREIGN KEY (ID_ORGAO) REFERENCES BA_ORGAO (ID_ORGAO)
);

-- Problemas do espaço público registrados pelos cidadãos
CREATE TABLE BA_OCORRENCIA (
  ID_OCORRENCIA NUMBER(10)     GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TITULO        VARCHAR2(100)  NOT NULL,
  DESCRICAO     VARCHAR2(1000) NOT NULL,
  ENDERECO      VARCHAR2(150)  NOT NULL,
  REFERENCIA    VARCHAR2(150),
  ID_BAIRRO     NUMBER(10)     NOT NULL,
  ID_CATEGORIA  NUMBER(10)     NOT NULL,
  ID_CIDADAO    NUMBER(10)     NOT NULL,
  STATUS        VARCHAR2(15)   DEFAULT 'ABERTA' NOT NULL,
  DT_ABERTURA   DATE           DEFAULT SYSDATE NOT NULL,
  DT_RESOLUCAO  DATE,
  CONSTRAINT PK_BA_OCORRENCIA PRIMARY KEY (ID_OCORRENCIA),
  CONSTRAINT FK_BA_OCORRENCIA_BAIRRO FOREIGN KEY (ID_BAIRRO) REFERENCES BA_BAIRRO (ID_BAIRRO),
  CONSTRAINT FK_BA_OCORRENCIA_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES BA_CATEGORIA (ID_CATEGORIA),
  CONSTRAINT FK_BA_OCORRENCIA_CIDADAO FOREIGN KEY (ID_CIDADAO) REFERENCES BA_CIDADAO (ID_CIDADAO),
  CONSTRAINT CK_BA_OCORRENCIA_STATUS CHECK (STATUS IN ('ABERTA', 'EM_ANALISE', 'EM_ANDAMENTO', 'RESOLVIDA', 'CANCELADA')),
  CONSTRAINT CK_BA_OCORRENCIA_DATAS CHECK (DT_RESOLUCAO IS NULL OR DT_RESOLUCAO >= DT_ABERTURA)
);

-- N:N - cada cidadão apoia várias ocorrências e cada ocorrência recebe vários apoios.
-- A PK composta impede que a mesma pessoa apoie duas vezes.
CREATE TABLE BA_APOIO (
  ID_CIDADAO    NUMBER(10) NOT NULL,
  ID_OCORRENCIA NUMBER(10) NOT NULL,
  DT_APOIO      DATE       DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_BA_APOIO PRIMARY KEY (ID_CIDADAO, ID_OCORRENCIA),
  CONSTRAINT FK_BA_APOIO_CIDADAO FOREIGN KEY (ID_CIDADAO) REFERENCES BA_CIDADAO (ID_CIDADAO) ON DELETE CASCADE,
  CONSTRAINT FK_BA_APOIO_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA) REFERENCES BA_OCORRENCIA (ID_OCORRENCIA) ON DELETE CASCADE
);

-- Histórico de atendimento: cada mudança de status feita por um servidor público
CREATE TABLE BA_ATUALIZACAO (
  ID_ATUALIZACAO  NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_OCORRENCIA   NUMBER(10)    NOT NULL,
  ID_SERVIDOR     NUMBER(10)    NOT NULL,
  STATUS_ANTERIOR VARCHAR2(15)  NOT NULL,
  STATUS_NOVO     VARCHAR2(15)  NOT NULL,
  COMENTARIO      VARCHAR2(500) NOT NULL,
  DT_ATUALIZACAO  DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_BA_ATUALIZACAO PRIMARY KEY (ID_ATUALIZACAO),
  CONSTRAINT FK_BA_ATUALIZACAO_OCORRENCIA FOREIGN KEY (ID_OCORRENCIA) REFERENCES BA_OCORRENCIA (ID_OCORRENCIA) ON DELETE CASCADE,
  CONSTRAINT FK_BA_ATUALIZACAO_SERVIDOR FOREIGN KEY (ID_SERVIDOR) REFERENCES BA_SERVIDOR (ID_SERVIDOR),
  CONSTRAINT CK_BA_ATUALIZACAO_STATUS CHECK (STATUS_NOVO IN ('ABERTA', 'EM_ANALISE', 'EM_ANDAMENTO', 'RESOLVIDA', 'CANCELADA')),
  CONSTRAINT CK_BA_ATUALIZACAO_MUDANCA CHECK (STATUS_NOVO <> STATUS_ANTERIOR)
);

CREATE INDEX IX_BA_OCORRENCIA_STATUS ON BA_OCORRENCIA (STATUS);
CREATE INDEX IX_BA_OCORRENCIA_BAIRRO ON BA_OCORRENCIA (ID_BAIRRO);
CREATE INDEX IX_BA_OCORRENCIA_CATEGORIA ON BA_OCORRENCIA (ID_CATEGORIA);
CREATE INDEX IX_BA_OCORRENCIA_CIDADAO ON BA_OCORRENCIA (ID_CIDADAO);
CREATE INDEX IX_BA_APOIO_OCORRENCIA ON BA_APOIO (ID_OCORRENCIA);
CREATE INDEX IX_BA_ATUALIZACAO_OCORRENCIA ON BA_ATUALIZACAO (ID_OCORRENCIA);

