-- Ocorrências por bairro: total, abertas, resolvidas e tempo médio de resolução
SELECT b.NOME AS BAIRRO, b.ZONA,
       COUNT(o.ID_OCORRENCIA) AS TOTAL,
       SUM(CASE WHEN o.STATUS IN ('ABERTA', 'EM_ANALISE', 'EM_ANDAMENTO') THEN 1 ELSE 0 END) AS PENDENTES,
       SUM(CASE WHEN o.STATUS = 'RESOLVIDA' THEN 1 ELSE 0 END) AS RESOLVIDAS,
       ROUND(AVG(o.DT_RESOLUCAO - o.DT_ABERTURA), 1) AS DIAS_MEDIOS_RESOLUCAO
  FROM BA_BAIRRO b
  LEFT JOIN BA_OCORRENCIA o ON o.ID_BAIRRO = b.ID_BAIRRO
 GROUP BY b.NOME, b.ZONA
 ORDER BY PENDENTES DESC, TOTAL DESC;

-- Categorias: volume, pendências fora do prazo e apoios recebidos
SELECT c.NOME AS CATEGORIA, c.PRAZO_DIAS,
       COUNT(DISTINCT o.ID_OCORRENCIA) AS TOTAL,
       COUNT(DISTINCT CASE WHEN o.STATUS IN ('ABERTA', 'EM_ANALISE', 'EM_ANDAMENTO')
                            AND TRUNC(SYSDATE - o.DT_ABERTURA) > c.PRAZO_DIAS THEN o.ID_OCORRENCIA END) AS ATRASADAS,
       COUNT(a.ID_CIDADAO) AS APOIOS
  FROM BA_CATEGORIA c
  LEFT JOIN BA_OCORRENCIA o ON o.ID_CATEGORIA = c.ID_CATEGORIA
  LEFT JOIN BA_APOIO a ON a.ID_OCORRENCIA = o.ID_OCORRENCIA
 GROUP BY c.NOME, c.PRAZO_DIAS
 ORDER BY TOTAL DESC;

-- Fila de cada órgão: pendências por órgão responsável
SELECT g.SIGLA, g.NOME AS ORGAO,
       COUNT(o.ID_OCORRENCIA) AS PENDENTES,
       SUM(CASE WHEN TRUNC(SYSDATE - o.DT_ABERTURA) > c.PRAZO_DIAS THEN 1 ELSE 0 END) AS FORA_DO_PRAZO
  FROM BA_ORGAO g
  JOIN BA_CATEGORIA c ON c.ID_ORGAO = g.ID_ORGAO
  LEFT JOIN BA_OCORRENCIA o ON o.ID_CATEGORIA = c.ID_CATEGORIA
                           AND o.STATUS IN ('ABERTA', 'EM_ANALISE', 'EM_ANDAMENTO')
 GROUP BY g.SIGLA, g.NOME
 ORDER BY PENDENTES DESC;

-- Ranking das ocorrências pendentes mais apoiadas
SELECT o.ID_OCORRENCIA, o.TITULO, b.NOME AS BAIRRO, c.NOME AS CATEGORIA,
       COUNT(a.ID_CIDADAO) AS APOIOS, TRUNC(SYSDATE - o.DT_ABERTURA) AS DIAS_EM_ABERTO
  FROM BA_OCORRENCIA o
  JOIN BA_BAIRRO b ON b.ID_BAIRRO = o.ID_BAIRRO
  JOIN BA_CATEGORIA c ON c.ID_CATEGORIA = o.ID_CATEGORIA
  LEFT JOIN BA_APOIO a ON a.ID_OCORRENCIA = o.ID_OCORRENCIA
 WHERE o.STATUS IN ('ABERTA', 'EM_ANALISE', 'EM_ANDAMENTO')
 GROUP BY o.ID_OCORRENCIA, o.TITULO, b.NOME, c.NOME, o.DT_ABERTURA
 ORDER BY APOIOS DESC, DIAS_EM_ABERTO DESC;
